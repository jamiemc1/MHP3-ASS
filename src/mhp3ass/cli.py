def _default_data_dir() -> Path:
    # Until the data is packaged, it's read from the checkout's legacy/Run/Data.
    data_dir = Path(__file__).resolve().parents[2] / "legacy" / "Run" / "Data"
    return data_dir


def _whole_number(text: str) -> int:
    value = int(text)
    if value < 0:
        raise argparse.ArgumentTypeError("needs a whole number of at least 0")
    return value


def _positive_number(text: str) -> int:
    value = int(text)
    if value < 1:
        raise argparse.ArgumentTypeError("needs a whole number of at least 1")
    return value


def _import_save(args: argparse.Namespace) -> int:
    """The import dialog with its defaults: the first character with charms, Select
    Best's ticks, then Import (which replaces the list)."""
    game = load_game_data(args.data_dir)
    tables = generate_charm_tables(game)
    apply_language(game, args.data_dir / "Languages" / args.lang)
    validity = build_charm_validity(tables, ability_count=len(game.abilities))
    try:
        save_import = read_save(args.save.read_bytes(), game, validity)
    except SaveFileError as error:
        print(f"{args.save}: {error}", file=sys.stderr)
        return 1
    charms = default_import(save_import, game)
    save_my_charms(args.out, charms)
    character = save_import.default_character
    if character is None:
        print(f"No character in {args.save} has charms; wrote an empty list to {args.out}")
        return 0
    hacked = sum(imported.charm.hacked for imported in character.charms)
    print(
        f"Character {character.slot + 1}: {len(character.charms)} charms, "
        f"{len(charms)} kept by Select Best, {hacked} hacked skipped; wrote {args.out}"
    )
    if save_import.cheats:
        print("Some charms in this save can't be generated by the game (hacked).")
    return 0


def _print_progress(progress: WorkerProgress) -> None:
    template = progress.worker.template
    name = "no charm" if template is None else charm_name(template)
    print(
        f"worker {progress.number + 1}/{progress.worker_count} {name}: "
        f"{len(progress.worker.found):,} found, {len(progress.worker.added):,} added, "
        f"{progress.seconds:.1f} s",
        file=sys.stderr,
    )


def _search(args: argparse.Namespace) -> int:
    """The harness's ``search``: the same inputs, the same output files.

    Exit codes: 0 done (also with no solutions or no workers), 1 bad input,
    3 the original would have thrown (with ``--record-exceptions`` a worker's
    throw is recorded instead, as the harness does). A port error the
    original has no counterpart for propagates.
    """
    try:
        # utf-8-sig: the harness's File::ReadAllText skips a byte order mark.
        spec_json = json.loads(args.query.read_text(encoding="utf-8-sig"))
        spec = SearchSpec.from_json(spec_json)
    except (OSError, ValueError, KeyError, TypeError) as error:
        # Unreadable file, invalid JSON or query (QueryError is a ValueError),
        # a missing field, a field of the wrong JSON type.
        print(f"{args.query}: {error}", file=sys.stderr)
        return 1
    on_worker_done = _print_progress if args.progress else None
    with ExitStack() as stack:
        pool = stack.enter_context(SearchPool(jobs=args.jobs)) if args.jobs > 1 else None
        if pool is not None:
            # The processes boot while this one builds the charm tables.
            pool.start()
        try:
            data = SearchData.load(args.data_dir, language=spec.query.language)
        except (OSError, ValueError, KeyError, TypeError) as error:
            # Unreadable or malformed data files, an unknown language.
            print(f"{args.query}: {error}", file=sys.stderr)
            return 1
        try:
            # Recorded in any case, so a throw can name its worker; reported
            # below as the harness reports it.
            result = run_search(
                spec,
                data=data,
                record_exceptions=True,
                on_worker_done=on_worker_done,
                pool=pool,
            )
        except (QueryError, MyCharmsFileError) as error:
            # The skill checks and the my-charms lines, which need the game.
            print(f"{args.query}: {error}", file=sys.stderr)
            return 1
        except (LegacyNullReferenceError, LookupError) as error:
            exception_type = dotnet_exception_type(error)
            if exception_type is None:
                raise
            # Outside the workers: duplicate removal's HashArmor (quirk T).
            print(f"{args.query}: outside the workers: {exception_type}", file=sys.stderr)
            return 3
    exception = result.exception
    if exception is not None and not args.record_exceptions:
        name = "no charm" if exception.template is None else charm_name(exception.template)
        print(
            f"{args.query}: worker {exception.worker + 1}/{result.worker_count} ({name}): "
            f"{exception.type}",
            file=sys.stderr,
        )
        return 3
    if not args.record_exceptions:
        result = replace(result, exceptions_recorded=False)
    lines = solution_lines(result, game=data.game)
    if args.out is None:
        try:
            for line in lines:
                print(line)
            sys.stdout.flush()
        except BrokenPipeError:
            # The reader stopped early (`| head`); without this Python reports
            # the closed pipe again at exit.
            devnull = os.open(os.devnull, os.O_WRONLY)
            os.dup2(devnull, sys.stdout.fileno())
            return 0
    else:
        manifest = search_manifest(
            spec_json, result=result, game=data.game, max_solution_lines=args.max_solution_lines
        )
        candidates = candidate_lines(result, game=data.game) if args.candidates else None
        write_search_outputs(args.out, manifest=manifest, lines=lines, candidates=candidates)
    found = sum(len(worker.found) for worker in result.workers)
    print(
        f"{len(lines):,} solutions from {result.worker_count} workers ({found:,} found)",
        file=sys.stderr,
    )
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="mhp3-ass",
        description="Armor set search for Monster Hunter Portable 3rd.",
    )
    parser.add_argument("--version", action="version", version=f"%(prog)s {__version__}")
    commands = parser.add_subparsers(dest="command")
    import_save = commands.add_parser(
        "import-save",
        help="write a my-charms file from your MHP3rd save, as the GUI's import does",
    )
    import_save.add_argument("save", type=Path, help="your MHP3RD.BIN save file")
    import_save.add_argument(
        "--out", type=Path, required=True, help="the my-charms file to write (replaced)"
    )
    import_save.add_argument(
        "--lang", default="English (TeamHGG)", help="language folder for skill names"
    )
    import_save.add_argument(
        "--data-dir", type=Path, default=_default_data_dir(), help="the game data folder"
    )
    search = commands.add_parser(
        "search",
        help="run a query file's search, writing what the harness's search writes",
    )
    search.add_argument("query", type=Path, help="a query file in the corpus format")
    search.add_argument(
        "--out",
        type=Path,
        help="write PREFIX.manifest.json and PREFIX.solutions.txt.gz; without it, "
        "solution lines go to stdout",
    )
    search.add_argument(
        "--candidates",
        action="store_true",
        help="also write PREFIX.candidates.txt.gz: every solution found, before duplicate removal",
    )
    search.add_argument(
        "--max-solution-lines",
        type=_whole_number,
        default=-1,
        help="leave out the solutions file when there are more lines than this",
    )
    search.add_argument(
        "--record-exceptions",
        action="store_true",
        help="record a worker the original would throw in, in the manifest, instead of failing",
    )
    search.add_argument(
        "--progress",
        action="store_true",
        help="report each finished worker on stderr (with --jobs above 1, every worker once "
        "the pool has finished, with the time its merge took)",
    )
    search.add_argument(
        "--jobs",
        type=_positive_number,
        default=default_jobs(),
        help="processes to search in (default: one per CPU, at most 8); 1 searches in this "
        "process, the workers in turn",
    )
    search.add_argument(
        "--data-dir", type=Path, default=_default_data_dir(), help="the game data folder"
    )
    args = parser.parse_args(argv)
    if args.command == "import-save":
        return _import_save(args)
    if args.command == "search":
        if args.out is None and (args.candidates or args.max_solution_lines >= 0):
            parser.error("--candidates and --max-solution-lines need --out")
        try:
            return _search(args)
        except KeyboardInterrupt:
            # Files are only written once the search has finished.
            return 130
    if not (sys.stdin.isatty() and sys.stdout.isatty()):
        parser.print_help()
        return 0
    exit_code = _run_tui(_default_data_dir())
    return exit_code


def _run_tui(data_dir: Path) -> int:
    """The app, with the pool's processes booting while the data loads.

    Until the saved-data folder exists, my charms are the data folder's
    ``mycharms.txt``, where the original keeps them (``Data/mycharms.txt``).
    """
    languages_dir = data_dir / "Languages"
    language = default_language(language_folders(languages_dir))
    if language is None:
        raise FileNotFoundError(f"no language folders in {languages_dir}")
    jobs = default_jobs()
    with ExitStack() as stack:
        pool = stack.enter_context(SearchPool(jobs=jobs)) if jobs > 1 else None
        if pool is not None:
            pool.start()
        data = SearchData.load(data_dir, language=language)
        app = SearchApp(
            language=language,
            data=data,
            strings=load_strings(languages_dir / language),
            form=QueryForm.starting(),
            pool=pool,
            my_charms_path=data_dir / "mycharms.txt",
        )
        app.run()
    exit_code = app.return_code if app.return_code is not None else 0
    return exit_code
